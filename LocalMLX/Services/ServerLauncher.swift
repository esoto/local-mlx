import Foundation
import AppKit

/// Writes an executable `.command` file that starts `mlx_lm.server` with a
/// user-chosen model and opens it in Terminal. This is a deliberate
/// workaround for the macOS app sandbox: we never call `Process.run`
/// ourselves (which would require relaxing the sandbox); instead, we hand
/// a script to the OS via `NSWorkspace.open`, which routes it to Terminal
/// — an unsandboxed agent — and that's what executes the server. Closing
/// the Terminal window stops the server.
enum ServerLauncher {

    struct Config: Equatable {
        /// Model identifier or on-disk path accepted by `mlx_lm.server --model`.
        var modelPath: String
        /// Optional Python virtualenv to `source` before running the server.
        /// Pass an empty string to skip and use whatever is on the user's PATH.
        var pythonVenvPath: String
        /// Port the server should listen on, derived from the configured
        /// base URL in `AppSettings`.
        var port: Int
    }

    /// Render the shell script without performing any I/O. Split out of
    /// `write(_:to:)` so tests can assert content independently.
    static func renderScript(_ config: Config) -> String {
        let trimmedVenv = config.pythonVenvPath
            .trimmingCharacters(in: .whitespacesAndNewlines)
        let model = shellEscape(config.modelPath)

        var lines: [String] = [
            "#!/bin/bash",
            "# Generated by LocalMLX — do not edit by hand.",
            "# Closing this Terminal window stops the server.",
            "set -eu",
            "echo 'LocalMLX → starting mlx_lm.server on port \(config.port)…'",
        ]
        if !trimmedVenv.isEmpty {
            let venv = shellEscape(trimmedVenv)
            lines.append("# Activate the configured virtualenv.")
            lines.append("source \(venv)/bin/activate")
        }
        lines.append("exec mlx_lm.server --model \(model) --port \(config.port)")
        return lines.joined(separator: "\n") + "\n"
    }

    /// Single-quote escape a path/identifier for safe embedding in bash.
    /// Keeps the implementation defensive against model paths with spaces
    /// or special characters.
    static func shellEscape(_ string: String) -> String {
        "'" + string.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// Default on-disk location inside the app's Application Support
    /// container. Safe to write under the sandbox.
    static func defaultCommandFileURL() throws -> URL {
        let fm = FileManager.default
        let base = try fm.url(
            for: .applicationSupportDirectory,
            in: .userDomainMask,
            appropriateFor: nil,
            create: true)
        let dir = base.appendingPathComponent("LocalMLX", isDirectory: true)
        try fm.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("start-mlx-server.command")
    }

    /// Write the rendered script to `url` and mark it executable.
    /// Returns the URL so the caller can chain to `launch(_:)`. Split
    /// from `launch` so unit tests can verify content + permissions
    /// without actually spawning Terminal.
    @discardableResult
    static func write(_ config: Config, to url: URL) throws -> URL {
        let script = renderScript(config)
        try script.write(to: url, atomically: true, encoding: .utf8)
        var attrs = try FileManager.default.attributesOfItem(atPath: url.path)
        attrs[.posixPermissions] = NSNumber(value: 0o755)
        try FileManager.default.setAttributes(attrs, ofItemAtPath: url.path)
        return url
    }

    /// Hand the command file to Launch Services so Terminal runs it.
    static func launch(_ url: URL) {
        NSWorkspace.shared.open(url)
    }

    /// Convenience: write to the default location and launch. The side
    /// effect (`launch`) is isolated so tests call `write` directly.
    @discardableResult
    static func writeAndLaunch(_ config: Config) throws -> URL {
        let url = try defaultCommandFileURL()
        _ = try write(config, to: url)
        launch(url)
        return url
    }
}
